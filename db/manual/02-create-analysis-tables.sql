-- PostgreSQL 17, local database with both parent tables and neither analysis table.
BEGIN;
DO $$
BEGIN
    IF current_database() <> 'irion_dev' OR current_schema() IS DISTINCT FROM 'public' THEN
        RAISE EXCEPTION 'Expected irion_dev/public';
    END IF;
END $$;

CREATE TABLE public.analysis_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    startup_condition_id bigint NOT NULL,
    title varchar(255),
    status varchar(20) NOT NULL,
    candidate_property_ids jsonb NOT NULL,
    condition_snapshot jsonb NOT NULL,
    assumptions_snapshot jsonb,
    calculation_version varchar(255),
    data_cutoff_at timestamp(6) without time zone,
    horizon_months integer,
    completed_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_analysis_runs_startup_condition FOREIGN KEY (startup_condition_id)
        REFERENCES public.startup_conditions(id),
    CONSTRAINT ck_analysis_runs_status CHECK (status IN ('PROCESSING', 'COMPLETED', 'FAILED'))
);
CREATE INDEX idx_analysis_runs_startup_condition_id ON public.analysis_runs (startup_condition_id);

CREATE TABLE public.property_analyses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id bigint NOT NULL REFERENCES public.analysis_runs(id),
    candidate_property_id bigint NOT NULL REFERENCES public.candidate_properties(id),
    property_snapshot jsonb NOT NULL,
    expected_monthly_sales bigint,
    monthly_fixed_cost bigint,
    variable_cost_rate numeric,
    monthly_operating_profit bigint,
    break_even_sales bigint,
    break_even_status varchar(255),
    initial_required_cash bigint,
    initial_operating_cash bigint,
    safety_score numeric,
    safety_grade varchar(255),
    recommendation_rank integer,
    recommendation_reason text,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL
);
CREATE INDEX idx_property_analyses_analysis_run_id ON public.property_analyses (analysis_run_id);
COMMIT;
