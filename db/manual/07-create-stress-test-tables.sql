BEGIN;
CREATE TABLE public.stress_tests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_analysis_id bigint NOT NULL REFERENCES public.property_analyses(id) ON DELETE CASCADE,
    sales_decrease_percent integer NOT NULL CHECK (sales_decrease_percent IN (0, 10, 20, 30)),
    safety_score numeric(5,2) NOT NULL CHECK (safety_score BETWEEN 0 AND 100),
    safety_grade varchar(255) NOT NULL CHECK (safety_grade IN ('A', 'B', 'C')),
    depletion_status varchar(255) NOT NULL,
    depletion_month_index integer,
    UNIQUE (property_analysis_id, sales_decrease_percent),
    CHECK ((depletion_status = 'DEPLETED' AND depletion_month_index IS NOT NULL AND depletion_month_index BETWEEN 0 AND 12)
        OR (depletion_status = 'NOT_DEPLETED' AND depletion_month_index IS NULL))
);

CREATE TABLE public.monthly_cash_flows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stress_test_id bigint NOT NULL REFERENCES public.stress_tests(id) ON DELETE CASCADE,
    month_index integer NOT NULL CHECK (month_index BETWEEN 1 AND 12),
    opening_cash bigint NOT NULL,
    sales bigint NOT NULL,
    variable_cost bigint NOT NULL,
    fixed_cost bigint NOT NULL,
    loan_interest bigint NOT NULL,
    principal_repayment bigint NOT NULL,
    net_cash_flow bigint NOT NULL,
    closing_cash bigint NOT NULL,
    UNIQUE (stress_test_id, month_index),
    CHECK (net_cash_flow = sales - variable_cost - fixed_cost - loan_interest - principal_repayment),
    CHECK (closing_cash = opening_cash + net_cash_flow)
);
COMMIT;
